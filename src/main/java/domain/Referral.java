package domain;

import lombok.AllArgsConstructor;
import lombok.Getter;
import lombok.Setter;

@Getter 
@Setter 
@AllArgsConstructor
public class Referral {
    private final int id; //automatically generated by db TODO: make db table
    private final String referringPhysician;
    private final String referralType;
    private final String requestedSpecialty;
    private final String requestedProfessional;
    private final String clinicalReason;
    private final String priority;
    private String status; // will prob switch to enum but don't have values yet

    //remove this when db implemented for referral
    public Referral(String referringPhysician, String referralType, String requestedSpecialty, String requestedProfessional, String clinicalReason, String priority, String status) {
        this.referringPhysician = referringPhysician;
        this.referralType = referralType;
        this.requestedSpecialty = requestedSpecialty;
        this.requestedProfessional = requestedProfessional;
        this.clinicalReason = clinicalReason;
        this.priority = priority;
        this.status = status;

        this.id = 0; //this would be bad practice...
    }
}
